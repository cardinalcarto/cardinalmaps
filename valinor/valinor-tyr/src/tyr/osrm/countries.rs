//! Country tables the OSRM serializer uses: ISO 3166-1 alpha-3 codes for leg `admins`
//! (mainline's `baldr::get_iso_3166_1_alpha3`, from `src/baldr/admin.cc`)
//! and speed limit sign conventions for `speedLimitSign` and `speedLimitUnit`
//! (`speed_limit_info` in `route_serializer_osrm.cc`).

/// Vienna convention speed limit signs.
pub(super) const SPEED_LIMIT_SIGN_VIENNA: &str = "vienna";
/// MUTCD speed limit signs.
const SPEED_LIMIT_SIGN_MUTCD: &str = "mutcd";
/// Kilometers per hour.
pub(super) const SPEED_LIMIT_UNITS_KPH: &str = "km/h";
/// Miles per hour.
const SPEED_LIMIT_UNITS_MPH: &str = "mph";

/// The speed limit sign style and unit of a country (by alpha-2 code),
/// defaulting to Vienna convention signs in km/h.
pub(super) fn speed_limit_info(alpha2: &str) -> (&'static str, &'static str) {
    match alpha2 {
        "CA" | "LR" => (SPEED_LIMIT_SIGN_MUTCD, SPEED_LIMIT_UNITS_KPH),
        "GU" | "PR" | "US" | "VI" => (SPEED_LIMIT_SIGN_MUTCD, SPEED_LIMIT_UNITS_MPH),
        "AG" | "AI" | "AS" | "BS" | "BZ" | "DM" | "FK" | "GB" | "GD" | "GG" | "GS" | "IM"
        | "JE" | "KN" | "KY" | "LC" | "MP" | "MS" | "SH" | "TC" | "VC" | "VG" | "WS" => {
            (SPEED_LIMIT_SIGN_VIENNA, SPEED_LIMIT_UNITS_MPH)
        }
        _ => (SPEED_LIMIT_SIGN_VIENNA, SPEED_LIMIT_UNITS_KPH),
    }
}

