#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn lookups() {
        assert_eq!(iso_3166_1_alpha3("AD"), Some("AND"));
        assert_eq!(iso_3166_1_alpha3("XK"), Some("XKX"));
        assert_eq!(iso_3166_1_alpha3("ZZ"), None);
        assert_eq!(speed_limit_info("US"), ("mutcd", "mph"));
        assert_eq!(speed_limit_info("CA"), ("mutcd", "km/h"));
        assert_eq!(speed_limit_info("GB"), ("vienna", "mph"));
        assert_eq!(speed_limit_info("AD"), ("vienna", "km/h"));
        assert_eq!(speed_limit_info(""), ("vienna", "km/h"));
    }
}
